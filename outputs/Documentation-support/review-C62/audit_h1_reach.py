"""Read installed client POB/FLR data; emit metadata only, never extracted assets.

Run in WSL as swgemu, at nice 19 while the owner plays. Mirrors the pinned
0262d8de floor triangle AABB calculation; not an engine visibility benchmark.
"""
import hashlib
import math
from pathlib import Path
import re
import struct
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / 'tools'))
from swgfmt import trn_iff as iff

index = iff.client_index()
cache = {}

def raw(name):
    return iff.open_tre_entry(str(Path(iff.CLIENT) / index[name]), name)

def floor_bounds(name):
    if name in cache:
        return cache[name]
    data = raw(name)
    roots = iff.parse(data)
    assert iff.build(roots)==data, name
    tree = list(iff.walk(roots))
    version = tree[1][1].form
    assert version in ('0003','0005','0006'), (name,version)
    verts = next(n.data for _,n in tree if n.tag=='VERT')
    tris = next(n.data for _,n in tree if n.tag=='TRIS')
    if version=='0006':
        assert struct.unpack_from('<I',verts)[0] * 12 == len(verts)-4
        assert struct.unpack_from('<I',tris)[0] * 60 == len(tris)-4
        verts, tris = verts[4:], tris[4:]
    assert len(verts)%12==0 and len(tris)%60==0
    vertices=list(struct.iter_unpack('<fff',verts))
    used={i for start in range(0,len(tris),60) for i in struct.unpack_from('<iii',tris,start)}
    if not used:
        answer = (0, hashlib.sha256(data).hexdigest())
    else:
        points=[vertices[i] for i in used]
        x=max(abs(p[0]) for p in points)
        z=max(abs(p[2]) for p in points)
        answer = (math.hypot(x,z), hashlib.sha256(data).hexdigest())
    cache[name]=answer
    return answer

records=[]
counts={}
no_cells=[]
unsupported=[]
errors=[]
for name,archive in sorted(index.items()):
    if not name.endswith('.pob'):
        continue
    group='mtg' if 'mtg' in archive.lower() else 'local' if 'local' in archive.lower() else 'stock'
    counts[group]=counts.get(group,0)+1
    try:
        data=raw(name)
        if not data:
            no_cells.append(name)
            continue
        roots=iff.parse(data)
        assert iff.build(roots)==data, name
        if not roots[0].children:
            no_cells.append(name)
            continue
        version=roots[0].children[0]
        if version.form not in ('0003','0004'):
            unsupported.append((name,version.form))
            continue  # PortalLayout::parse rejects these too
        cels=next((n for n in version.children if n.form=='CELS'),None)
        if cels is None:
            no_cells.append(name)
            continue
        floors=[]
        for cell in cels.children:
            v=cell.children[0]
            assert cell.form=='CELL' and v.form in ('0004','0005'), (name,cell.form,v.form)
            chunk=next(n.data for n in v.children if n.tag=='DATA')
            # int portal count, byte, NUL cell name, NUL appearance name,
            # byte floor-present, then NUL floor filename. CellProperty::loadVersion4/5.
            at=5
            for _ in range(2):
                at=chunk.index(b'\0',at)+1
            present=chunk[at]; at+=1
            if present:
                floor=chunk[at:chunk.index(b'\0',at)].decode()
                assert floor in index, (name,floor)
                reach,sha=floor_bounds(floor)
                floors.append((reach,floor,sha))
        if floors:
            reach,floor,sha=max(floors)
            if reach>96:
                records.append(dict(pob=name,archive=archive,group=group,reach=reach,
                                    floor=floor,floor_sha256=sha,pob_sha256=hashlib.sha256(data).hexdigest(),templates=[]))
    except Exception as error:
        errors.append((name,repr(error)))
by_pob={r['pob']:r for r in records}
for name in sorted(index):
    if name.startswith('object/building/') and name.endswith('.iff'):
        data=raw(name)
        for pob in set(s.decode() for s in re.findall(rb'appearance/[\w/.-]+\.pob',data)):
            if pob in by_pob:
                by_pob[pob]['templates'].append(name)
stock=sorted((r for r in records if r['group']=='stock'), key=lambda r:(-r['reach'],r['pob']))
lines=['# H1 stock building reach inventory','',
       'Installed archive metadata, 18 October 2026. Generated by `audit_h1_reach.py`; engine pin `0262d8de`.',
       'Reach is the maximum per-floor horizontal AABB-corner distance, from triangle vertices; range = 192 + reach.',
       'These are template effects on newly initialized objects; pre-fix saved radius fields can override them (C65 N2).',
       f"Scanned {counts.get('stock',0)} stock and {counts.get('mtg',0)} MTG winning layouts; {len(stock)} stock layouts exceed 96 m.",
       f"No-cell layouts (no floors to enlarge): {', '.join('`'+x+'`' for x in no_cells)}.",
       'Engine-unsupported layout versions: '+', '.join(f'`{n}` (`{v}`)' for n,v in unsupported)+'.',
       f'Parse errors: {len(errors)}. All matched object templates below are client definitions, not a count of spawned server objects.','',
       '| Portal layout (`appearance/` prefix omitted) | Reach m | New range m | Client building template(s), `object/building/` omitted |',
       '|---|---:|---:|---|']
for r in stock:
    templates='<br>'.join('`'+t.removeprefix('object/building/')+'`' for t in r['templates']) or '(none found)'
    lines.append(f"| `{r['pob'].removeprefix('appearance/')}` | {r['reach']:.2f} | {192+r['reach']:.2f} | {templates} |")
lines += ['', '## Largest custom layout', '']
for r in records:
    if 'echo_base' in r['pob']:
        lines.append(f"`{r['pob']}`: reach {r['reach']:.2f} m; range {192+r['reach']:.2f} m; winning archive `{r['archive']}`.")
lines += ['', '## Input fingerprints', '', 'Only hashes and names are recorded; no game assets are copied.', '',
          '| Layout | Layout SHA-256 | Limiting floor | Floor SHA-256 |', '|---|---|---|---|']
for r in stock:
    lines.append(f"| `{r['pob']}` | `{r['pob_sha256']}` | `{r['floor']}` | `{r['floor_sha256']}` |")
(HERE/'H1-stock-buildings.md').write_bytes(('\r\n'.join(lines)+'\r\n').encode())
print(f'Scanned {counts}; {len(stock)} stock layouts >96 m; {len(errors)} errors; no-cell layouts {no_cells}')
print('Engine-unsupported versions:',unsupported)
for error in errors: print('ERROR',error)
if errors: sys.exit(1)
