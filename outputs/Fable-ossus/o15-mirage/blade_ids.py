"""Ossus O15 mirage: the ids of the blade pixel programs the hook looks for (Claude, 18 Oct 2026).

The id is FNV-1a (32 bit) over a ps_2_0 token stream with its comment blocks (the constant table) left out. mirage.c
takes the same sum in CreatePixelShader. These programs count as a blade:
  stock  pixel_program/e_h_lightsaberblade_ps20.psh from the client's base archives (any archive but local_planets)
  every  pixel_program/*blade*_ps20.psh in the installed local_planets.tre (on a2610d64: the O14 saber blade and the
         light whip blade), so a newer install only needs this script run again and the proxy rebuilt

--tre can be given more than once: the installed archive and the ones queued for the next swap, so one proxy build
matches before and after it (18 Oct: b9fbc48a installed, the O14 4c5a29d0 chains queued).
Writes src/blade_ids.h, and each program's code to work/o15-mirage/test for the test harness: <name>_blade.pexe for
the first archive's programs, <name>_blade_<id>.pexe for one that only a later archive has.
Usage: python blade_ids.py [--tre <local_planets.tre>]...
"""
import argparse
import glob
import hashlib
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUTS = os.path.dirname(os.path.dirname(HERE))
H = os.path.dirname(OUTPUTS)
sys.path.insert(0, os.path.join(OUTPUTS, 'tools'))
from swgfmt import tre_write  # noqa: E402
from swgfmt import trn_iff  # noqa: E402

CLIENT = os.path.join(OUTPUTS, 'SWG-client')
PSH = 'pixel_program/e_h_lightsaberblade_ps20.psh'
STOCK_LINE = b'diffuseColor.rgb = saturate (diffuseColor.rgb + diffuseColor.a);'
TEST_DIR = os.path.join(H, 'work', 'o15-mirage', 'test')


def pexe(psh):
    nodes = trn_iff.parse(psh)
    ver = nodes[0].children[0]
    assert nodes[0].form == 'PSHP' and ver.form == '0000', 'not a pixel program'
    return [c for c in ver.children if c.tag == 'PEXE'][0].data


def psrc(psh):
    return [c for c in trn_iff.parse(psh)[0].children[0].children if c.tag == 'PSRC'][0].data


def shader_id(code):
    """FNV-1a over the version token and every instruction (SM2 length bits), skipping comment blocks."""
    t = struct.unpack('<%dI' % (len(code) // 4), code[:len(code) // 4 * 4])
    h = 0x811C9DC5

    def mix(h, tok):
        for b in struct.pack('<I', tok):
            h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
        return h

    h = mix(h, t[0])
    i = 1
    while i < len(t):
        tok = t[i]
        if tok & 0xFFFF == 0xFFFE:
            i += 1 + ((tok >> 16) & 0x7FFF)
            continue
        if tok == 0x0000FFFF:
            return mix(h, tok)
        n = (tok >> 24) & 0xF
        for k in range(i, i + 1 + n):
            h = mix(h, t[k])
        i += 1 + n
    raise ValueError('no end token')


def stock_blade():
    """The stock program from the base archives (local_planets.tre overrides it on the installed client)."""
    for path in sorted(glob.glob(os.path.join(CLIENT, '*.tre'))):
        if os.path.basename(path).lower().startswith('local_planets'):
            continue
        if PSH in trn_iff.list_tre(path):
            data = trn_iff.open_tre_entry(path, PSH)
            if STOCK_LINE in psrc(data):
                return data, os.path.basename(path)
    raise SystemExit('stock %s not found in the base archives' % PSH)


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument('--tre', action='append')
    args = ap.parse_args(argv)
    tres = args.tre or [os.path.join(CLIENT, 'local_planets.tre')]

    stock, stock_from = stock_blade()
    # [short name, code, what, test file stem]
    rows = [['stock', pexe(stock), 'stock e_h_lightsaberblade_ps20 (%s)' % stock_from, 'stock_blade']]
    for n, tre in enumerate(tres):
        raw = open(tre, 'rb').read()
        tre_sha = hashlib.sha256(raw).hexdigest()
        ours = tre_write.read(raw)[0]
        for name in sorted(ours):
            if name.startswith('pixel_program/') and 'blade' in name and name.endswith('_ps20.psh'):
                short = 'saber' if name == PSH else os.path.basename(name).split('_')[2].replace('blade', '')
                code = pexe(ours[name])
                same = [r for r in rows if shader_id(r[1]) == shader_id(code)]
                if same:
                    if tre_sha[:8] not in same[0][2]:
                        same[0][2] += ', %s' % tre_sha[:8]
                    continue
                stem = '%s_blade' % short if n == 0 else '%s_blade_%08x' % (short, shader_id(code))
                rows.append([short, code, '%s in local_planets.tre %s' % (os.path.basename(name), tre_sha[:8]), stem])
    for name, code, what, stem in rows:
        assert code[:4] == b'\x00\x02\xff\xff', '%s is not ps_2_0' % name

    lines = ['// Generated by blade_ids.py (Ossus O15 mirage): ids of the blade pixel programs.',
             '// FNV-1a over the ps_2_0 token stream without comment blocks; mirage.c takes the same sum.',
             '#define BLADE_ID_COUNT %d' % len(rows),
             'static const unsigned int BLADE_IDS[BLADE_ID_COUNT] = {']
    for name, code, what, stem in rows:
        lines.append('    0x%08xu,  // %s, code sha256 %s' % (shader_id(code), what, hashlib.sha256(code).hexdigest()[:16]))
    lines.append('};')
    with open(os.path.join(HERE, 'src', 'blade_ids.h'), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

    os.makedirs(TEST_DIR, exist_ok=True)
    for name, code, what, stem in rows:
        with open(os.path.join(TEST_DIR, '%s.pexe' % stem), 'wb') as f:
            f.write(code)
    for name, code, what, stem in rows:
        print('%-5s 0x%08x  %d bytes  %s' % (name, shader_id(code), len(code), what))


if __name__ == '__main__':
    main(sys.argv[1:])
