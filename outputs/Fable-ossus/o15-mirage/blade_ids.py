"""Ossus O15 mirage: the ids of the lightsaber blade pixel programs the hook looks for (Claude, 18 Oct 2026).

The id is FNV-1a (32 bit) over a ps_2_0 token stream with its comment blocks (the constant table) left out. mirage.c
takes the same sum in CreatePixelShader. Two programs count as the blade:
  stock  pixel_program/e_h_lightsaberblade_ps20.psh from the client's own archives (in effect on the installed c8a61080)
  O14    the crystal-aware replacement in work/ossus-ghostfire-crystal (892475a4, built, not installed)

Writes src/blade_ids.h, and both programs' code to work/o15-mirage/test (stock_blade.pexe, o14_blade.pexe) for the
test harness.
Usage: python blade_ids.py [--o14 <archive>]
"""
import argparse
import hashlib
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUTS = os.path.dirname(os.path.dirname(HERE))
H = os.path.dirname(OUTPUTS)
sys.path.insert(0, os.path.join(OUTPUTS, 'tools'))
from swgfmt import tre_write  # noqa: E402
from swgfmt import trn_iff  # noqa: E402

PSH = 'pixel_program/e_h_lightsaberblade_ps20.psh'
O14_TRE = os.path.join(H, 'work', 'ossus-ghostfire-crystal', 'local_planets-ghostfire-crystal.tre')
O14_CODE_SHA = 'd8c1157e331f0845f0c5acdefcc76628c0cdbac748ecde68d5a1bb172ff5140d'   # checks-crystal.json
TEST_DIR = os.path.join(H, 'work', 'o15-mirage', 'test')


def pexe(psh):
    nodes = trn_iff.parse(psh)
    ver = nodes[0].children[0]
    assert nodes[0].form == 'PSHP' and ver.form == '0000', 'not a pixel program'
    return [c for c in ver.children if c.tag == 'PEXE'][0].data


def shader_id(code):
    """FNV-1a over the version token and every instruction (SM2 length bits), skipping comment blocks."""
    t = struct.unpack('<%dI' % (len(code) // 4), code[:len(code) // 4 * 4])
    h = 0x811C9DC5

    def mix(h, tok):
        for b in struct.pack('<I', tok):
            h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
        return h

    h = mix(h, t[0])
    i = 1
    while i < len(t):
        tok = t[i]
        if tok & 0xFFFF == 0xFFFE:
            i += 1 + ((tok >> 16) & 0x7FFF)
            continue
        if tok == 0x0000FFFF:
            return mix(h, tok)
        n = (tok >> 24) & 0xF
        for k in range(i, i + 1 + n):
            h = mix(h, t[k])
        i += 1 + n
    raise ValueError('no end token')


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument('--o14', default=O14_TRE)
    args = ap.parse_args(argv)

    stock = pexe(trn_iff.client_file(PSH))
    o14 = pexe(tre_write.read(open(args.o14, 'rb').read())[0][PSH])
    assert hashlib.sha256(o14).hexdigest() == O14_CODE_SHA, 'O14 code is not the one in checks-crystal.json'
    assert stock[:4] == o14[:4] == b'\x00\x02\xff\xff', 'not ps_2_0'
    rows = [('stock', stock, 'stock e_h_lightsaberblade_ps20.psh from the client archives'),
            ('o14', o14, 'O14 crystal-aware replacement (archive 892475a4)')]

    lines = ['// Generated by blade_ids.py (Ossus O15 mirage): ids of the lightsaber blade pixel programs.',
             '// FNV-1a over the ps_2_0 token stream without comment blocks; mirage.c takes the same sum.',
             '#define BLADE_ID_COUNT %d' % len(rows),
             'static const unsigned int BLADE_IDS[BLADE_ID_COUNT] = {']
    for name, code, what in rows:
        lines.append('    0x%08xu,  // %s, code sha256 %s' % (shader_id(code), what, hashlib.sha256(code).hexdigest()[:16]))
    lines.append('};')
    with open(os.path.join(HERE, 'src', 'blade_ids.h'), 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

    os.makedirs(TEST_DIR, exist_ok=True)
    for name, code, what in rows:
        with open(os.path.join(TEST_DIR, '%s_blade.pexe' % name), 'wb') as f:
            f.write(code)
    for name, code, what in rows:
        print('%-5s 0x%08x  %d bytes  %s' % (name, shader_id(code), len(code), hashlib.sha256(code).hexdigest()))


if __name__ == '__main__':
    main(sys.argv[1:])
