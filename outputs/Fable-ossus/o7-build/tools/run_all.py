"""O7 end to end, nothing in the repo's staged files touched: build the terrain with and without the o7 layers (temp folders),
survey it, regenerate statics.json / poi-placements.json / template-resolution.json, test the snapshot append, and write
../checks.json. About four minutes. Read-only on the client archives and on /opt/swg (the server-template list comes from
tools/server_check.sh, run separately inside WSL).

    python -I run_all.py
"""
import filecmp
import math
import os
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from o7_common import EXISTING_WS, O7, OSSUS, STAGED_CLIENT, STAGED_TRN, Census, Terrain, jload, jsave  # noqa: E402
import append_snapshot as AS  # noqa: E402
import make_o7  # noqa: E402
import o7_terrain as OT  # noqa: E402


def main():
    t0 = time.time()
    tmp = tempfile.mkdtemp(prefix='o7-run-')
    o7_dir, plain_dir = os.path.join(tmp, 'o7'), os.path.join(tmp, 'plain')
    print('building the plain terrain (no o7 layers) ...')
    plain = OT.build(plain_dir, with_layers=False, quiet=True)
    print('building the o7 terrain ...')
    new = OT.build(o7_dir, with_layers=True, quiet=True)
    sc = os.path.join(o7_dir, 'staged', 'client')
    same = {f: filecmp.cmp(os.path.join(plain_dir, 'staged', 'client', f), os.path.join(STAGED_CLIENT, f), shallow=False)
            for f in ('terrain/ossus.trn', 'terrain/ossus_academy.tga', 'terrain/ossus_canyon.tga', 'terrain/ossus_mesa.tga')}
    tga_same = {f: filecmp.cmp(os.path.join(sc, f), os.path.join(STAGED_CLIENT, f), shallow=False) for f in ('terrain/ossus_academy.tga', 'terrain/ossus_canyon.tga', 'terrain/ossus_mesa.tga')}
    import trn_read
    trn_new = trn_read.read_trn(open(os.path.join(sc, 'terrain', 'ossus.trn'), 'rb').read())
    trn_old = trn_read.read_trn(open(STAGED_TRN, 'rb').read())
    terrain = {
        'build_verdict_with_o7_layers': new['verdict'], 'build_verdict_plain': plain['verdict'],
        'plain_build_byte_identical_to_staged': same, 'o7_build_tgas_identical_to_staged': tga_same,
        'bytes_staged': os.path.getsize(STAGED_TRN), 'bytes_o7': os.path.getsize(os.path.join(sc, 'terrain', 'ossus.trn')),
        'top_layers_staged': len(trn_old['layers']), 'top_layers_o7': len(trn_new['layers']),
        'round_trip_identical': new['round_trip_identical'], 'core3_order_notes': new['core3_order_notes'],
        'core3_order_notes_unexpected': new['core3_order_notes_unexpected'], 'structure_pairs_not_in_stock': new['structure_pairs_not_in_stock'],
        'references_missing': new['references_missing'], 'reference_counts': new['reference_counts'], 'rule_counts': new['rule_counts'],
        'sites_unchanged': {k: (new['sites'][k] == plain['sites'][k]) if k in new['sites'] else None for k in ('starport_pad', 'academy_ruins', 'caves')},
        'camp_probes': {'staged_plain': [c['probe']['spread'] for c in plain['sites']['camps']], 'o7': [c['probe']['spread'] for c in new['sites']['camps']]},
    }
    print('surveying ...')
    survey = OT.survey(sc)
    print('generating statics and placements ...')
    make_o7.main(['--terrain', o7_dir])
    statics = jload(os.path.join(O7, 'statics.json'))
    checks_statics = jload(os.path.join(O7, 'out', 'checks-statics.json'))
    print('testing the snapshot append ...')
    data, info = AS.build(statics, EXISTING_WS)
    problems, rep = AS.check(data, statics)
    rep.update(info)
    rep['problems'] = problems
    # the 87 existing nodes sit on unchanged ground
    from swgfmt import ws_read
    nodes, _ = ws_read.read_ws(open(EXISTING_WS, 'rb').read())
    T_new, T_old = Terrain(os.path.join(sc, 'terrain', 'ossus.trn'), sc), Terrain()
    shift = max(abs(T_new.h(n['x'], n['y']) - T_old.h(n['x'], n['y'])) for n in nodes if n['depth'] == 0)
    # the terrain model against the census (z is truncated to whole metres there, so compare with z + 0.5)
    census = Census()
    errs = [abs(T_old.h(r['x'], r['y']) - (r['z'] + 0.5)) for r in census.rows if r['kind'] != 'building' and r['name'] != 'Transport Shuttle']
    errs.sort()
    srv = [l.split() for l in open(os.path.join(O7, 'out', 'server-templates.txt'), encoding='utf-8') if l.strip() and not l.startswith('#')]
    header = open(os.path.join(O7, 'out', 'server-templates.txt'), encoding='utf-8').readline().strip()
    checks = {
        'what': 'Generated by tools/run_all.py (about four minutes). Numbers are from the Core3 height port of the built terrain and the client archives; nothing here was run in a client or on the galaxy.',
        'terrain': terrain, 'terrain_survey': survey,
        'statics': {k: v for k, v in checks_statics.items() if k not in ('templates_table',)},
        'building_node_vs_stock': {r['template'].split('/')[-1]: r['building_node_vs_stock'] for r in checks_statics['templates_table'] if r['portal_layout']},
        'snapshot_append': rep,
        'existing_snapshot_nodes_max_ground_shift_m': round(shift, 4),
        'census_vs_terrain_model': {'samples': len(errs), 'median_abs_error_m': round(errs[len(errs) // 2], 2), 'p95_m': round(errs[int(len(errs) * .95)], 2), 'max_m': round(errs[-1], 2),
                                    'note': 'abs(terrain port - (census z + 0.5)); the census z is int() of a metre value, so about 0.5 m is rounding'},
        'server_templates': {'file': 'out/server-templates.txt', 'header': header, 'ok': sum(1 for r in srv if r[0] == 'ok'), 'missing': [r[1] for r in srv if r[0] != 'ok']},
        'seconds': round(time.time() - t0),
    }
    jsave(os.path.join(O7, 'checks.json'), checks)
    print('wrote checks.json in %d s' % checks['seconds'])
    ok = (new['verdict'] == 'PASS' and plain['verdict'] == 'PASS' and all(same.values()) and not problems and not checks_statics['overlaps']
          and not checks_statics['template_problems'])
    print('ALL CHECKS', 'PASS' if ok else 'CHECK')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
