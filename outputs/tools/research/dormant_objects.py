"""Dormant client objects: object definitions in the client archives that the server has no template for.

These are the cut-content candidates whose assets you already own. Reads only archive indexes (file names),
never file contents, and changes nothing.

Inside Debian (as swgemu):
  python3 dormant_objects.py [--tre /opt/swg/tre] [--scripts /opt/swg/Core3-dev/MMOCoreORB/bin/scripts]

Writes outputs/Content-catalogue/dormant-client-objects.json and .md.
"""
from pathlib import Path
import collections, json, struct, sys, zlib

OUT = Path(__file__).resolve().parents[2] / 'Content-catalogue'


def tre_names(path):
    """File names in a version 5 TRE archive's index."""
    with path.open('rb') as f:
        magic, version, count, offset, ftype, fsize, ntype, nsize, usize = struct.unpack('<4s4s7I', f.read(36))
        if magic != b'EERT' or version != b'5000':
            raise ValueError(f'unsupported {magic!r} {version!r}')
        f.seek(offset)
        records = f.read(fsize if ftype == 2 else count * 24)
        if ftype == 2:
            records = zlib.decompress(records)
        names = f.read(nsize if ntype == 2 else usize)
        if ntype == 2:
            names = zlib.decompress(names)
    for i in range(count):
        start = struct.unpack_from('<6I', records, i * 24)[5]
        yield names[start:names.find(b'\0', start)].decode('latin1')


def main():
    args = sys.argv[1:]
    tre = Path(args[args.index('--tre') + 1]) if '--tre' in args else Path('/opt/swg/tre')
    scripts = Path(args[args.index('--scripts') + 1]) if '--scripts' in args else Path('/opt/swg/Core3-dev/MMOCoreORB/bin/scripts')

    client = {}  # shared template path -> archives
    errors = []
    for archive in sorted(tre.glob('*.tre')):
        try:
            for name in tre_names(archive):
                if name.startswith('object/') and '/shared_' in name and name.endswith('.iff'):
                    client.setdefault(name, []).append(archive.name)
        except Exception as exc:
            errors.append(f'{archive.name}: {exc}')

    server = set()
    for lua in (scripts / 'object').rglob('*.lua'):
        if lua.name in ('objects.lua', 'serverobjects.lua'):
            continue
        server.add(str(lua.relative_to(scripts).with_suffix('.iff')).replace('\\', '/'))

    dormant = []
    for shared, archives in sorted(client.items()):
        folder, name = shared.rsplit('/', 1)
        if f'{folder}/{name[len("shared_"):]}' in server:
            continue
        origin = 'MTG' if all(a.startswith('mtg_') for a in archives) else 'SOE client'
        dormant.append({'object': shared, 'origin': origin, 'archives': archives})

    def category(path):
        parts = path.split('/')
        return '/'.join(parts[:3]) if len(parts) > 3 else '/'.join(parts[:2])

    counts = collections.Counter((d['origin'], category(d['object'])) for d in dormant)
    OUT.mkdir(exist_ok=True)
    (OUT / 'dormant-client-objects.json').write_text(json.dumps({
        'client_objects': len(client), 'server_templates': len(server), 'dormant': len(dormant),
        'errors': errors, 'objects': dormant}, indent=1), encoding='utf-8')

    lines = ['# Dormant client objects', '',
             f'Object definitions in the client archives (`{tre}`) with no server template in `{scripts}/object`.',
             'Generated by `tools/research/dormant_objects.py` (archive indexes only; nothing changed).', '',
             f'- client object definitions: {len(client)}', f'- server templates: {len(server)}',
             f'- **dormant: {len(dormant)}** (SOE client: {sum(1 for d in dormant if d["origin"] == "SOE client")}, '
             f'MTG: {sum(1 for d in dormant if d["origin"] == "MTG")})', '',
             'SOE-client entries are the cut-content candidates (assets you own; we write the server side). '
             'MTG entries come from MTG packages (check each package\'s terms). Many entries are harmless leftovers '
             '(test objects, unused variants); sort before planning.', '',
             '| Origin | Category | Dormant objects |', '|---|---|---|']
    for (origin, cat), n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f'| {origin} | `{cat}` | {n} |')
    lines += ['', '## SOE client examples (first 60)', '']
    lines += [f'- `{d["object"]}`' for d in dormant if d['origin'] == 'SOE client'][:60]
    if errors:
        lines += ['', '## Archives not read', ''] + [f'- {e}' for e in errors]
    (OUT / 'dormant-client-objects.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'client {len(client)}, server {len(server)}, dormant {len(dormant)}; errors {len(errors)}')
    for (origin, cat), n in counts.most_common(15):
        print(f'  {n:6d}  {origin:10s}  {cat}')


if __name__ == '__main__':
    main()
