"""Report for the launch simulation (server-side bots playing new characters; BotPopLaunch.h in Core3-dev).

Reads the server's event log (bin/log/botpop-launch.jsonl on the test galaxy) and Claude's host samples
(Bot-reports/launch-sim/host-*.jsonl) and writes Bot-reports/launch-sim/numbers.md: the numbers only, grouped by
the roadmap themes they inform. Read-only on the server; stdlib only.

    python3 botpop_report.py [EVENTS.jsonl] [--host HOST.jsonl] [--out FILE.md] [--name run7] [--compare NAME=PATH ...]

botpop_analysis.py runs this for the newest run against all the others in one command.
"""
import argparse
import collections
import glob
import json
import os
import statistics
import sys
import time
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
from botpop_analysis import gameplay_rows, summarize, host_cutoff, GAP_BUCKETS

OUTPUTS = os.path.dirname(os.path.dirname(HERE))
SIM = os.path.join(OUTPUTS, 'Bot-reports', 'launch-sim')
EVENTS = '/opt/swg/testgalaxy/Core3/MMOCoreORB/bin/log/botpop-launch.jsonl'


def load(path):
    rows = []
    with open(path, encoding='utf-8', errors='replace') as f:
        for line in f:
            try:
                rows.append(json.loads(line))
            except ValueError:
                pass
    return rows


def median(values):
    return round(statistics.median(values), 1) if values else '-'


def pct(part, whole):
    return f'{100 * part / whole:.0f}%' if whole else '-'


def dash(value):
    return '-' if value is None else value


def when(ms):
    return time.strftime('%d %b %H:%M:%S', time.localtime(ms / 1000)) if ms else 'none'


def mission_cells(r):
    f = r['finish_minutes']
    return [r['taken'], r['done'], r['gone'], r['aborted'], r['pending'], pct(r['success'], r['taken']), pct(r['success'], r['resolved']),
            dash(f['median']), dash(f['p90']), dash(r['reward']['median']), dash(r['distance_m']['median'])]


def table(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(out)


def report(events, host, until_ms=None, comparisons=(), name='current'):
    run_label = name  # `name` is reused by loops below
    host_end = host_cutoff(events, host)
    until_ms = min(x for x in (until_ms,host_end) if x is not None) if until_ms is not None or host_end is not None else None
    summary = summarize(events, until_ms)
    events, _ = gameplay_rows(events, until_ms)
    by = collections.defaultdict(list)
    for r in events:
        by[r.get('e')].append(r)
    if not by['spawn']:
        return '# Launch simulation\n\nNo spawn rows yet.\n'

    t0 = min(r['t'] for r in by['spawn']) / 1000
    t1 = max(r['t'] for r in events) / 1000
    hours = max((t1 - t0) / 3600, 1e-6)
    all_host = host
    host = [r for r in host if t0 <= r.get('t', 0) <= t1]
    spawn = {r['bot']: r for r in by['spawn']}
    role_of = {b: r['role'] for b, r in spawn.items()}
    last = {}
    for r in by['snap']:
        last[r['bot']] = r
    roles = collections.Counter(role_of.values())
    md = [f"# Launch simulation: the numbers\n",
          f"{datetime.fromtimestamp(t0):%d %b %H:%M} to {datetime.fromtimestamp(t1):%H:%M} "
          f"({(t1 - t0) / 60:.0f} min), {len(spawn)} new characters in {len({r['city'] for r in spawn.values()})} cities; "
          f"roles: " + ', '.join(f'{k} {v}' for k, v in roles.most_common()) + ". Generated by `tools/bots/botpop_report.py`.\n"]

    compare = sorted([(n, rs if isinstance(rs, dict) else summarize(rs, host_cutoff(rs, all_host))) for n, rs in comparisons]
                     + [(run_label, summary)], key=lambda kv: kv[1].get('start_ms') or 0)
    md.append(f'## Runs compared (this report is about {run_label})\n')
    md.append(table(['run', 'started', 'minutes', 'bots', 'bot-hours', 'purse (median first snapshot)', 'boxes', 'training paid', 'missions taken', 'missions done', 'kills', 'deaths'],
                    [[n, time.strftime('%d %b %H:%M', time.localtime(r['start_ms'] / 1000)) if r.get('start_ms') else '-', r.get('minutes'), r.get('bots'),
                      r['bot_hours'], dash(r.get('purse_median')), r['training']['charged_boxes'] + r['training']['legacy_free_boxes'], r['training']['spent'],
                      r['missions_total']['taken'], r['missions_total']['done'], r.get('kills', '-'), r['deaths']] for n, r in compare]))
    md.append('')

    # Server capacity
    md.append('## Server capacity (ambient population, friends\' launch)\n')
    steps = collections.defaultdict(list)
    for r in host:
        b = r.get('botpop') or {}
        if b.get('online') and r.get('cores') is not None:
            steps[b['online']].append(r)
    rows = []
    for online in sorted(steps):
        rs = steps[online]
        rows.append([online, median([r['cores'] for r in rs]), max(r['rss_mb'] for r in rs),
                     min(r['wsl_avail_mb'] for r in rs), max((r['botpop'].get('pass_ms') or 0) for r in rs), len(rs)])
    if rows:
        md.append(table(['bots online', 'core3 cores (median)', 'core3 RSS MB (max)', 'WSL free MB (min)',
                         'tick ms (max)', 'samples'], rows))
    server = by['server']
    if server:
        peak = max(r.get('online', 0) for r in server)
        full = [r for r in server if r.get('online', 0) == peak]
        steady = full[1:] or full  # the first full-population row still carries the end of the ramp-up
        md.append(f"\nServer rows: {len(server)}, {len(full)} at the full {peak} bots (the rest are the ramp-up, where tick averages reach "
                  f"{max(r.get('tick_ms_avg', 0) for r in server)} ms). At full population: tick avg median {median([r.get('tick_ms_avg', 0) for r in steady])} ms, "
                  f"worst tick {max(r.get('tick_ms_max', 0) for r in steady)} ms, passes skipped {sum(r.get('skipped', 0) for r in steady)}, "
                  f"RSS {steady[0].get('rss_mb', 0)} to {steady[-1].get('rss_mb', 0)} MB.")
    errors = sum(r.get('new_error_lines', 0) for r in host)
    md.append(f"New ERROR lines in core3.log during the run: {errors}.\n")

    # Progression
    md.append('## Progression (sandbox XP and training cost, the first month\'s pacing)\n')
    trains = by['train']
    per_role = collections.defaultdict(list)
    for b, r in last.items():
        per_role[r['role']].append(r)
    rows = []
    for role in sorted(per_role):
        rs = per_role[role]
        boxes = [r['boxes'] for r in rs]
        first = [t['min'] for t in trains if role_of.get(t['bot']) == role and t['boxes'] == 1]
        rows.append([role, len(rs), sum(boxes), round(sum(boxes) / len(rs), 1), max(boxes), median(first),
                     round(sum(boxes) / hours / len(rs), 2), median([r['lvl'] for r in rs])])
    md.append(table(['role', 'bots', 'boxes', 'per bot', 'best', 'first box (min, median)', 'boxes/bot/hour',
                     'combat level (median)'], rows))
    skills = collections.Counter(t['skill'] for t in trains)
    md.append('\nBoxes trained, most common: ' + ', '.join(f'{k} {v}' for k, v in skills.most_common(15)) + '.')
    masters = [t for t in trains if t['skill'].endswith('_master')]
    md.append(f"Master boxes: {len(masters)}.")
    stuck = collections.Counter(r['want_xp'] for r in last.values() if r.get('want_xp'))
    md.append('Experience the next box waits for (latest snapshot): ' + ', '.join(f'{k} {v}' for k, v in stuck.most_common(10)) + '.\n')
    rates = collections.defaultdict(list)
    for r in last.values():
        for xp_type, amount in (r.get('xp') or {}).items():
            if amount:
                rates[(r['role'], xp_type)].append(amount / max(r['min'], 1) * 60)
    rows = [[role, xp_type, len(v), round(statistics.median(v))] for (role, xp_type), v in sorted(rates.items())]
    if rows:
        md.append(table(['role', 'experience', 'bots earning it', 'unspent per hour (median)'], rows))
        md.append('')

    # Combat and creatures
    md.append('## Combat and creatures (creature levels per planet, spawn density)\n')
    kills, deaths, incaps, aggro = by['kill'], by['death'], by['incap'], by['aggro']
    md.append(f"Kills {len(kills)} ({len(kills) / hours:.0f}/h), deaths {len(deaths)}, incapacitations {len(incaps)}, "
              f"creatures that attacked first {len(aggro)} ({pct(len(aggro), len(kills) + len(deaths))} of encounters), "
              f"give-ups {len(by['giveup'])}. Median time to kill {median([k['secs'] for k in kills])} s; median health "
              f"after a kill {median([k['health'] for k in kills])}%.\n")
    targets = collections.defaultdict(list)
    for k in kills:
        targets[k['target']].append(k)
    killers = collections.defaultdict(list)
    for d in deaths:
        killers[d.get('killer') or '?'].append(d)
    rows = []
    for name, ks in sorted(targets.items(), key=lambda kv: -len(kv[1]))[:25]:
        rows.append([name, len(ks), median([k['tlvl'] for k in ks]), len(killers.get(name, [])),
                     ', '.join(sorted({k['planet'] for k in ks}))])
    md.append(table(['creature', 'killed', 'level', 'killed a bot', 'planets'], rows))
    rows = [[name, len(ds), median([d.get('klvl', 0) for d in ds]), median([d.get('lvl', 0) for d in ds]),
             len(targets.get(name, [])), ', '.join(sorted({d['planet'] for d in ds}))]
            for name, ds in sorted(killers.items(), key=lambda kv: -len(kv[1]))[:15]]
    md.append('\nWhat kills new characters:\n')
    md.append(table(['killer', 'deaths', 'its level', 'bot level', 'times it was killed', 'planets'], rows))
    city = collections.defaultdict(lambda: [0, 0, 0, 0])
    for k in kills:
        city[(k['planet'], k['city'])][0] += 1
    for d in deaths:
        city[(d['planet'], d['city'])][1] += 1
    for w in by['widen']:
        city[(w['planet'], w['city'])][2] += 1
    for r in last.values():
        city[(r['planet'], r['city'])][3] += 1
    rows = [[p, c, v[3], v[0], v[1], pct(v[1], v[0] + v[1]), v[2]] for (p, c), v in sorted(city.items(), key=lambda kv: -kv[1][0])]
    md.append('\nBy city (kills and deaths where they happened; bots now there):\n')
    md.append(table(['planet', 'city', 'bots now', 'kills', 'deaths', 'death share', 'hunting ground widened'], rows))
    md.append('')

    # Economy
    md.append('## Economy (income per bot-hour, training cost, phase 1 baseline)\n')
    cash = [r.get('cash', 0) + r.get('bank', 0) for r in last.values()]
    tr = summary['training']
    income = summary['income']
    md.append(f"Credits held now: total {sum(cash)}, median {median(cash)}, best {max(cash) if cash else 0}; "
              f"launch purse (median of each bot's first snapshot) {dash(summary['purse_median'])}. "
              f"Corpses looted {sum(r.get('loots',0) for r in last.values())}.\n")
    md.append('### Income per bot-hour, by source\n')
    parts = [income[k] for k in ('missions', 'junk', 'loot_residual')]
    md.append(table(['source', 'credits', 'credits/bot-hour'],
                    [[k, income[k]['credits'], dash(income[k]['per_bot_hour'])] for k in ('missions', 'junk', 'loot_residual')]
                    + [['all three', sum(p['credits'] for p in parts), round(sum(p['per_bot_hour'] or 0 for p in parts), 3)]]))
    md.append(f"\nMission credits come from mission_done.paid (from run 7 it adds back training taken from the bank). "
              f"Exposure: {summary['bot_hours']} bot-hours for event income, {income['loot_residual']['bot_hours']} for the snapshot residual.\n")
    md.append('### Income per bot-hour, by role\n')
    md.append(table(['role', 'bots', 'bot-hours', 'missions', 'junk', 'loot (residual)', 'all three', 'training paid', 'kills', 'deaths'],
                    [[role, v['bots'], v['bot_hours'], dash(v['missions']['per_bot_hour']), dash(v['junk']['per_bot_hour']),
                      dash(v['loot_residual']['per_bot_hour']), v['income_per_bot_hour'], dash(v['training_per_bot_hour']), v['kills'], v['deaths']]
                     for role, v in sorted(income['by_role'].items())]))
    md.append('\nEvery income column is credits per bot-hour; "training paid" is the cost side. Roles that never take missions or sell junk show 0.\n')
    md.append(income['method'])
    md.append(f"{income['inference']} Inferred payments: {income['mission_inferred_count']} / {income['mission_inferred_credits']} credits.\n")
    sells = by['sell']
    if sells:
        earned = sum(s.get('credits', 0) for s in sells)
        md.append(f"Junk dealer: {len(sells)} sales, {sum(s.get('items', 0) for s in sells)} items, {earned} credits "
                  f"({earned / hours / max(len(spawn), 1):.1f} credits per bot-hour; median sale {median([s.get('credits', 0) for s in sells])}).\n")
    md.append('### Training: credits spent and boxes refused\n')
    md.append(f"Paid {tr['spent']} credits for {tr['charged_boxes']} boxes ({dash(tr['spent_per_bot_hour'])} per bot-hour; median cost {dash(tr['cost_median'])}); "
              f"legacy free boxes {tr['legacy_free_boxes']}, nominal cost {tr['nominal_cost']}. Credits before paying, median: {dash(tr['credits_before_median'])}. "
              f"Check: each bot's running total (train.spent) adds up to {tr['spent_running_total']} credits, "
              + ('the same as the rows above.' if tr['spent_running_total'] == tr['spent'] else f"{abs(tr['spent'] - tr['spent_running_total'])} away from the rows above, so some train rows are missing or double-counted."))
    md.append(f"Refused for credits: {tr['refusal_rows']} rows, {tr['refused_bot_boxes']} distinct bot/box pairs, {tr['bots_refused']} bots; "
              f"median shortfall (cost minus credits) {dash(tr['refusal_shortfall']['median'])}, worst {dash(tr['refusal_shortfall']['max'])}. "
              f"A bot that cannot pay logs a row each time it cycles between unaffordable boxes, so count the distinct pairs.\n")
    md.append(table(['role', 'boxes', 'paid', 'paid per bot-hour', 'refused bot/box pairs', 'bots refused'],
                    [[role, v['boxes'], v['training_spent'], dash(v['training_per_bot_hour']), v['refused_bot_boxes'], v['refused_bots']]
                     for role, v in sorted(income['by_role'].items())]))
    if tr['refused_skills']:
        md.append('\nBoxes refused for credits (distinct bots): ' + ', '.join(f'{k} {v}' for k, v in tr['refused_skills'].items()) + '.')
    md.append('')

    md.append('## Missions (pending attempts are censored at the report boundary)\n')
    total = summary['missions_total']
    md.append(f"Taken {total['taken']}, done {total['done']}, gone {total['gone']}, aborted {total['aborted']}, pending {total['pending']}; "
              f"success {pct(total['success'], total['taken'])} of taken, {pct(total['success'], total['resolved'])} of resolved. "
              f"Minutes to finish (successes): median {dash(total['finish_minutes']['median'])}, 90th percentile {dash(total['finish_minutes']['p90'])}, "
              f"longest {dash(total['finish_minutes']['max'])}. Outcomes: {json.dumps(summary['mission_outcomes'])}"
              + (f"; {summary['mission_outcomes_unmatched']} outcomes with no mission_take in the log are left out of the tables" if summary['mission_outcomes_unmatched'] else '') + '.')
    md.append('Resolved = done, gone or aborted (aborted = 20 minutes without finishing); success = done, plus old logs\' payments inferred from the reward. '
              'Pending attempts are excluded from success/resolved. "Bot level" is the level at acceptance.\n')
    head = ['taken', 'done', 'gone', 'aborted', 'pending', 'success/taken', 'success/resolved', 'minutes to finish (median)', 'p90', 'reward (median)', 'trip m (median)']
    md.append('### By bot level and mission level\n')
    md.append(table(['bot level', 'mission level'] + head, [[r['bot_level'], r['mission_level']] + mission_cells(r) for r in summary['missions_by_level']]))
    for title, key, field in (('By bot level', 'missions_by_bot_level', 'bot_level'), ('By mission level', 'missions_by_mission_level', 'mission_level'),
                              ('By level gap (mission level minus bot level)', 'missions_by_level_gap', 'level_gap'), ('By role', 'missions_by_role', 'role')):
        md.append(f'\n### {title}\n')
        md.append(table([title[3:].split(' (')[0]] + head, [[dash(r[field])] + mission_cells(r) for r in summary[key]]))
    md.append('')
    md.append('Other rows: ' + ', '.join(f"{k} {len(by[k])}" for k in ('mission_none', 'terminal', 'explore', 'seen')) + '. '
              f"Terminals found in {sum(1 for t in summary['terminals'] if t['found'])} of {len(summary['terminals'])} cities; "
              f"mission_none offered (median / max): {dash(summary['mission_none_offered']['median'])} / {dash(summary['mission_none_offered']['max'])}.")
    md.append('Lair distance from the mission spot (metres): ' + json.dumps(summary['lair_from_spot_m']) +
              '; seconds from taking the mission to finding the lair: ' + json.dumps(summary['lair_find_secs']) + '.\n')
    lairs = sorted(summary['lairs_by_name'].items(), key=lambda kv: (-kv[1], kv[0]))
    md.append(table(['lair (top 15 of %d)' % len(lairs), 'finds'], lairs[:15]))
    md.append('')

    md.append('## Spawn level gate (deaths by killer level minus bot level, by run)\n')
    md.append(table(['run', 'bot-hours', 'deaths', 'deaths/bot-hour', 'killer level known', 'median gap', 'killer >= bot + 8', 'share of known'],
                    [[n, r['bot_hours'], r['deaths'], r['deaths_per_bot_hour'], r['death_gap']['known'], dash(r['death_gap']['median']),
                      r['killer_at_least_8_above'], pct(r['killer_at_least_8_above'], r['death_gap']['known'])] for n, r in compare]))
    md.append("\nGap = the killer's level minus the dead bot's level; deaths whose killer is unknown (level 0) are left out. Share of deaths in each gap band (count in brackets):\n")
    md.append(table(['gap'] + [n for n, r in compare],
                    [[label] + [f"{pct(r['deaths_by_gap_bucket'].get(label, 0), r['death_gap']['known'])} ({r['deaths_by_gap_bucket'].get(label, 0)})"
                                for n, r in compare] for label, lo, hi in GAP_BUCKETS]))
    md.append('\nDeaths per 1,000 bot-hours in each gap band:\n')
    md.append(table(['gap'] + [n for n, r in compare],
                    [[label] + [round(1000 * r['deaths_by_gap_bucket'].get(label, 0) / r['bot_hours'], 1) if r['bot_hours'] else '-' for n, r in compare]
                                for label, lo, hi in GAP_BUCKETS]))
    md.append('\nDescriptive comparison: runs differ in duration, purse, population (including explorers), missions and bot behaviour; this does not isolate the gate as a cause. '
              'The gate is in dev b20a46d7, so runs 6 and later have it.\n')
    if summary['gate_leaks']:
        md.append(f'Killers 8 or more levels above the bot in {run_label}:\n')
        md.append(table(['killer', 'level', 'planet', 'deaths'], [[g['killer'], g['killer_level'], g['planet'], g['deaths']] for g in summary['gate_leaks']]))
        md.append('')
    md.append('Final despawn excluded (rows at or after the boundary are dropped from every table above):\n')
    md.append(table(['run', 'boundary (local)', 'how found', 'rows dropped', 'of them mission_gone'],
                    [[n, when(r['exclusion']['cutoff_ms']), r['exclusion']['reason'] or 'none found', r['exclusion']['excluded_rows'],
                      r['exclusion'].get('excluded_mission_gone', '-')] for n, r in compare]))
    md.append('')
    md.append('## Ossus census\n')
    md.append(f"Explorers requested: {summary['explorers_requested']}; seen rows {len(by['seen'])}. Seen rows are observations, not a unique-object census (no object IDs); "
              f"the census itself is `tools/bots/ossus_census.py`.\n")
    md.append(table(['planet', 'kind', 'name', 'observations'],
                    [[r['planet'], r['kind'], r['name'], r['observations']] for r in summary['census']]))
    md.append('')

    # Support roles
    md.append('## Medics and entertainers (social professions)\n')
    rested = by['rested']
    md.append(f"Hunters went home to rest {len(rested)} times; {sum(1 for r in rested if r.get('watched'))} watched a dancer; "
              f"{sum(1 for r in rested if r.get('full'))} left with full pools. Medic heals queued: "
              f"{sum(r.get('heals', 0) for r in last.values())}.\n")

    # Travel and coverage
    md.append('## Travel and coverage (planets, Ossus and Hoth, the bots\' map)\n')
    flows = collections.Counter((t['planet'], t['to_planet'], t['reason']) for t in by['travel'])
    md.append('Travel: ' + (', '.join(f'{a} to {b} ({why}) {n}' for (a, b, why), n in flows.most_common()) or 'none') + '.')
    squares = collections.defaultdict(set)
    for r in by['snap'] + kills + deaths:
        squares[r['planet']].add((int(r['x'] // 100), int(r['y'] // 100)))
    md.append('Outdoor 100 m squares with a bot in them (snapshots, kills, deaths): ' +
              ', '.join(f'{p} {len(s)}' for p, s in sorted(squares.items(), key=lambda kv: -len(kv[1]))) +
              f" (a planet is 16,384 squares).\n")
    states = collections.Counter(r.get('state') for r in by['snap'])
    md.append('Time split (all snapshots): ' + ', '.join(f'{k} {pct(v, sum(states.values()))}' for k, v in states.most_common()) + '.\n')
    return '\n'.join(md) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--name', default='current', help='label for this run in the comparison tables')
    parser.add_argument('events', nargs='?', default=EVENTS)
    parser.add_argument('--host', action='append')
    parser.add_argument('--out', default=os.path.join(SIM,'numbers.md'))
    parser.add_argument('--until-ms', type=int)
    parser.add_argument('--compare', action='append', default=[], metavar='NAME=PATH')
    args = parser.parse_args(argv)
    host_files = args.host or sorted(glob.glob(os.path.join(SIM,'host-*.jsonl')))
    host = [r for f in host_files for r in load(f)]
    comparisons = [(n,load(p)) for n,p in (x.split('=',1) for x in args.compare)]
    text = report(load(args.events), host, args.until_ms, comparisons, name=args.name)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {args.out} ({len(text)} chars)')


if __name__ == '__main__':
    main()
