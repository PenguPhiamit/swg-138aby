#!/usr/bin/env python3
"""Writes the launch bots' researched buying orders as a C++ header (BotPopBuilds.h) from the JSON block at the end
of Documentation-support/precu-player-builds.md (section 8: {"style": {"250": [box, ...], "1000": [...]}}).

    python3 tools/bots/gen_builds.py OUT.h

The header gives launchBuildOrder(style, skillPoints): a nullptr-terminated list of skill boxes in buying order for
LAUNCH_STYLES[style] (BotPopLaunch.h: sampler, hunter, tank, support), or nullptr for an unknown style.
"""
import json
import re
import sys
from pathlib import Path

DOC = Path(__file__).resolve().parents[2] / 'Documentation-support' / 'precu-player-builds.md'
STYLES = ['sampler', 'hunter', 'tank', 'support']  # the order of LAUNCH_STYLES


def main():
    out = Path(sys.argv[1])
    blocks = re.findall(r'```json\s*(\{.*?\})\s*```', DOC.read_text(encoding='utf-8'), re.S)
    builds = json.loads(blocks[-1])
    lines = ['// Generated by tools/bots/gen_builds.py from Documentation-support/precu-player-builds.md (section 8);',
             '// do not edit by hand. The launch bots\' researched buying orders per multiclass style and skill points.',
             '', '#pragma once', '', 'namespace botpop {', '']
    for style in STYLES:
        for sp in ('250', '1000'):
            boxes = builds[style][sp]
            assert all(re.fullmatch(r'[a-z0-9_]+', b) for b in boxes), (style, sp)
            lines.append('static const char* const BUILD_%s_%s[] = {' % (style.upper(), sp))
            for i in range(0, len(boxes), 4):
                lines.append('\t' + ' '.join('"%s",' % b for b in boxes[i:i + 4]))
            lines.append('\tnullptr};')
            lines.append('')
    lines.append('inline const char* const* launchBuildOrder(int style, int skillPoints) {')
    lines.append('\tswitch (style) {')
    for i, style in enumerate(STYLES):
        lines.append('\tcase %d:' % i)
        lines.append('\t\treturn skillPoints <= 250 ? BUILD_%s_250 : BUILD_%s_1000;' % (style.upper(), style.upper()))
    lines += ['\tdefault:', '\t\treturn nullptr;', '\t}', '}', '', '} // namespace botpop', '']
    out.write_text('\n'.join(lines), encoding='utf-8')
    print('%s: %s' % (out, ', '.join('%s %s/%s' % (s, len(builds[s]['250']), len(builds[s]['1000'])) for s in STYLES)))


if __name__ == '__main__':
    main()
