"""Generate the sandbox test datapad's creature list from Core3's mobile templates (Claude, 15 Oct 2026; owner: "add all
creatures to the dev menu ... organize them better"). Inside Debian:

    python3 sandbox_menus.py [--summary FILE]

Reads /opt/swg/Core3-dev/MMOCoreORB/bin/scripts/mobile/**.lua and writes
bin/scripts/screenplays/sandbox/sandbox_creatures.lua: every creature (mobType herbivore or carnivore), grouped by the
folder it lives in (a planet, or dungeon, lair, quest, event ...), sorted by name, each labelled with its level and
whether it can be tamed in the normal game (tamingChance > 0; on the test galaxy Core3.TameAnything tames any). Folders
of more than PAGE creatures are split into alphabetical pages. --summary appends one line per folder to FILE (for the
agent that writes menu descriptions).
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

SCRIPTS = Path('/opt/swg/Core3-dev/MMOCoreORB/bin/scripts')
OUT = SCRIPTS / 'screenplays' / 'sandbox' / 'sandbox_creatures.lua'
PAGE = 60
NAME = re.compile(r'CreatureTemplates:addCreatureTemplate\(\s*\w+\s*,\s*"([\w-]+)"\s*\)')
FIELD = lambda k: re.compile(r'\b%s\s*=\s*"?([^",\n]*)"?' % k)


def creatures():
    found = defaultdict(list)
    for path in sorted((SCRIPTS / 'mobile').rglob('*.lua')):
        text = path.read_text(errors='ignore')
        mob = FIELD('mobType').search(text)
        if not mob or mob.group(1).strip() not in ('MOB_HERBIVORE', 'MOB_CARNIVORE'):
            continue
        name = NAME.search(text)
        if not name:
            continue
        level = FIELD('level').search(text)
        tame = FIELD('tamingChance').search(text)
        shown = FIELD('objectName').search(text)
        label = (shown.group(1).split(':')[-1] if shown and shown.group(1) else name.group(1)).replace('_', ' ')
        try:
            tameable = float(tame.group(1)) > 0 if tame else False
        except ValueError:
            tameable = False
        lvl = level.group(1).strip() if level else '?'
        folder = path.relative_to(SCRIPTS / 'mobile').parts[0]
        found[folder.replace('.lua', '')].append((label, name.group(1), lvl, tameable))
    return found


def lua_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write(found, described=None):
    lines = ['-- Generated by outputs/tools/sandbox_menus.py from bin/scripts/mobile (do not edit by hand).',
             '-- Every creature (herbivore or carnivore) by folder, for the sandbox test datapad\'s spawn menu.',
             'SandboxCreatureFolders = {']
    for folder in sorted(found):
        rows = sorted(set(found[folder]), key=lambda r: (r[0].lower(), r[1]))
        pages = [rows[i:i + PAGE] for i in range(0, len(rows), PAGE)] or [[]]
        repeated = {label for label, *_ in rows if sum(1 for r in rows if r[0] == label) > 1}
        about = (described or {}).get(f'CREATURES > {folder}', '')
        lines.append(f'\t{{{lua_string(folder)}, {lua_string(about)}, {{')
        for page in pages:
            title = f'{page[0][0][:1].upper()}-{page[-1][0][:1].upper()}' if len(pages) > 1 else 'all'
            lines.append(f'\t\t{{{lua_string(title)}, {{')
            for label, template, lvl, tameable in page:
                text = f'{label} (level {lvl}{", tameable" if tameable else ""})'
                if label in repeated:  # two templates share a display name: say which one
                    text += f' [{template}]'
                lines.append(f'\t\t\t{{{lua_string(text)}, {lua_string(template)}}},')
            lines.append('\t\t}},')
        lines.append('\t}},')
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n')
    return sum(len(set(v)) for v in found.values())


PETS = SCRIPTS / 'object' / 'sandbox' / 'pet_deeds.lua'
DESCRIPTIONS = SCRIPTS / 'object' / 'sandbox' / 'menu_descriptions.lua'


def pet_deeds():
    """Every pet and droid deed template, labelled from its file name, for the character builder's Pets menu."""
    rows = {'Creature pets': [], 'Droids': []}
    for path in sorted((SCRIPTS / 'object' / 'tangible' / 'deed' / 'pet_deed').glob('*.lua')):
        stem = path.stem
        if stem in ('objects', 'serverobjects') or 'vehicular_prototype' in stem or stem.endswith('_base'):
            continue
        template = f'object/tangible/deed/pet_deed/{stem}.iff'
        if stem.startswith('deed_'):
            advanced = stem.endswith('_advanced_basic')
            base = stem[5:].replace('_advanced_basic', '').replace('_basic', '').replace('_', ' ')
            base = base.upper() if len(base) <= 4 else base.capitalize()
            rows['Droids'].append((base + (' (advanced)' if advanced else ''), template))
        else:
            rows['Creature pets'].append((stem.replace('_deed', '').replace('_', ' ').capitalize(), template))
    lines = ['-- Generated by outputs/tools/sandbox_menus.py (do not edit by hand): every pet and droid deed.',
             'SandboxPetDeeds = {']
    for group in ('Creature pets', 'Droids'):
        lines.append(f'\t{lua_string(group)}, {{')
        for name, template in sorted(rows[group]):
            lines.append(f'\t\t{lua_string(name)}, {lua_string(template)},')
        lines.append('\t},')
    lines.append('}')
    PETS.write_text('\n'.join(lines) + '\n')
    return {k: len(v) for k, v in rows.items()}


def descriptions(path):
    """The menu descriptions an agent wrote (JSON: section path -> text) as a Lua table."""
    import json
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    lines = ['-- Section descriptions for the character builder and the test datapad (written by a Claude agent from the',
             '-- section names and samples, 15 Oct 2026; generated by outputs/tools/sandbox_menus.py).',
             'SandboxMenuDescriptions = {']
    for key in sorted(data):
        lines.append(f'\t[{lua_string(key)}] = {lua_string(data[key])},')
    lines.append('}')
    DESCRIPTIONS.write_text('\n'.join(lines) + '\n')
    return len(data)


if __name__ == '__main__':
    found = creatures()
    described = {}
    if '--descriptions' in sys.argv:
        import json
        described = json.loads(Path(sys.argv[sys.argv.index('--descriptions') + 1]).read_text(encoding='utf-8'))
    total = write(found, described)
    print(f'{OUT}: {total} creatures in {len(found)} folders')
    print(f'{PETS}: {pet_deeds()}')
    if '--descriptions' in sys.argv:
        print(f"{DESCRIPTIONS}: {descriptions(sys.argv[sys.argv.index('--descriptions') + 1])} descriptions")
    if '--summary' in sys.argv:
        with open(sys.argv[sys.argv.index('--summary') + 1], 'a') as f:
            for folder in sorted(found):
                rows = sorted(set(found[folder]))
                f.write(f"CREATURES > {folder}\t{len(rows)} creatures\tsamples: {'; '.join(r[0] for r in rows[:4])}\n")
